# ================= CONVERTER =================

def convert_font(text: str, style: str) -> str:
    """
    Convert normal text into a selected font style.
    If style not found, returns original text.
    """
    table = FONT_MAP.get(style)
    if not table:
        return text
    return text.translate(table)

# ================= AVAILABLE STYLES =================

def available_fonts():
    """Return list of available font keys."""
    return list(FONT_MAP.keys())
